import os

class GitBookPlugin:
    def __init__(self):
        self.book_path = None

    def initialize(self, book_path):
        # Initialize the plugin with a book path
        self.book_path = book_path
        print(f"Initialized with book path: {self.book_path}")

    def execute(self):
        # Execute tasks related to the GitBook
        os.system(f'gitbook build {self.book_path}')
        print("GitBook built successfully")

    def shutdown(self):
        # Shutdown the plugin
        print("Plugin shutting down")
