import os
import json

class KnowledgeManagementPlugin:
    def __init__(self, config):
        self.config = config
        self.knowledge_base = {}

    def init(self):
        if os.path.exists(self.config['knowledge_file']):
            with open(self.config['knowledge_file'], 'r') as f:
                self.knowledge_base = json.load(f)
        else:
            print("No knowledge file found. Initializing an empty knowledge base.")

    def execute(self, query):
        response = None
        if query in self.knowledge_base:
            response = self.knowledge_base[query]
        return response

    def shutdown(self):
        with open(self.config['knowledge_file'], 'w') as f:
            json.dump(self.knowledge_base, f)
